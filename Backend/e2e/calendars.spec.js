import { test, expect } from '@playwright/test';
import { mockAdminApi } from './helpers/mockApi.js';

test('shared month calendar changes dashboard and reminder months without closing the reminder dialog', async ({ page }, testInfo) => {
  await mockAdminApi(page, { startAuthenticated: true });
  await page.goto('/');
  const dashboard = page.getByLabel('Dashboard month filter', { exact: true });
  const year = (await dashboard.inputValue()).slice(0, 4);
  await dashboard.click();
  const calendar = page.getByRole('dialog', { name: 'Choose month', exact: true });
  await expect(calendar).toBeVisible();
  await calendar.getByRole('button', { name: 'Sep', exact: true }).click();
  await expect(dashboard).toHaveValue(`${year}-09`);
  await expect(calendar).toBeHidden();
  await page.locator('button[aria-label="Billing"]:visible').click();
  await page.getByRole('button', { name: 'Send reminders', exact: true }).click();
  const reminder = page.getByRole('dialog', { name: 'Send payment reminders' });
  const month = reminder.getByLabel('Billing month', { exact: true });
  await month.click();
  await expect(calendar).toBeVisible();
  await calendar.getByRole('button', { name: 'Previous year', exact: true }).click();
  await calendar.getByRole('button', { name: 'Sep', exact: true }).click();
  await expect(month).toHaveValue(`${Number(year) - 1}-09`);
  await month.click();
  await page.keyboard.press('Escape');
  await expect(calendar).toBeHidden();
  await expect(reminder).toBeVisible();
  await month.click();
  const bounds = await calendar.boundingBox();
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(page.viewportSize().width);
  await page.screenshot({ path: testInfo.outputPath('month-calendar.png') });
});

test('shared day calendar preserves required fields, future-date limits and optional clearing inside tenant dialog', async ({ page }, testInfo) => {
  await mockAdminApi(page, { startAuthenticated: true });
  await page.goto('/');
  await page.locator('button[aria-label="Tenants"]:visible').click();
  await page.getByRole('button', { name: 'Add Tenant', exact: true }).click();
  const moveIn = page.getByLabel('Move-in date', { exact: true });
  await expect(moveIn).toBeVisible();
  expect(await moveIn.evaluate(input => input.required)).toBe(true);
  const max = await moveIn.getAttribute('max');
  await moveIn.click();
  const calendar = page.getByRole('dialog', { name: 'Choose date', exact: true });
  await expect(calendar).toBeVisible();
  await expect(calendar.getByRole('button', { name: 'Next month' })).toBeDisabled();
  const first = max.slice(0, 8) + '01';
  const label = new Date(first + 'T12:00:00').toLocaleDateString('en-PH', { month: 'long', day: 'numeric', year: 'numeric' });
  await calendar.getByRole('button', { name: label, exact: true }).click();
  await expect(moveIn).toHaveValue(first);
  await expect(moveIn.locator('..').locator('.calendar-value')).toHaveText(label);
  await moveIn.click();
  await page.screenshot({ path: testInfo.outputPath('day-calendar.png') });
  await page.keyboard.press('Escape');
  await expect(moveIn).toBeVisible();
  const end = page.getByLabel('Lease end date (optional)', { exact: true });
  await end.fill(first);
  await end.click();
  await calendar.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(end).toHaveValue('');
});
